create table if not exists public.exams (
 id bigint generated by default as identity primary key,
 title text not null,
 subject text not null default 'Programación I',
 questions jsonb not null,
 created_at timestamptz not null default now()
);
create table if not exists public.exam_publications (
 id bigint generated by default as identity primary key,
 exam_id bigint not null references public.exams(id) on delete cascade,
 group_name text not null,
 active boolean not null default true,
 published_at timestamptz not null default now(),
 unique(exam_id,group_name)
);
create table if not exists public.exam_results (
 id bigint generated by default as identity primary key,
 exam_id bigint not null references public.exams(id) on delete cascade,
 cedula text not null,
 student_name text not null,
 group_name text not null,
 correct_answers integer not null,
 total_questions integer not null,
 grade numeric(3,2) not null,
 status text not null check(status in ('APROBÓ','PERDIÓ')),
 submitted_at timestamptz not null default now(),
 unique(exam_id,cedula,group_name)
);
alter table public.exams enable row level security;
alter table public.exam_publications enable row level security;
alter table public.exam_results enable row level security;
revoke all on public.exams,public.exam_publications,public.exam_results from anon;
grant select,insert,update,delete on public.exams,public.exam_publications to authenticated;
grant select on public.exam_results to authenticated;
grant usage,select on all sequences in schema public to authenticated;
drop policy if exists exams_teacher_all on public.exams;
create policy exams_teacher_all on public.exams for all to authenticated using(auth.uid() is not null) with check(auth.uid() is not null);
drop policy if exists exam_publications_teacher_all on public.exam_publications;
create policy exam_publications_teacher_all on public.exam_publications for all to authenticated using(auth.uid() is not null) with check(auth.uid() is not null);
drop policy if exists exam_results_teacher_read on public.exam_results;
create policy exam_results_teacher_read on public.exam_results for select to authenticated using(auth.uid() is not null);

