create or replace function public.get_active_exam(p_cedula text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_student record; v_pub record; v_exam record; v_q jsonb;
begin
 select sr.cedula,sr.name,en.group_name into v_student
 from student_registry sr join student_enrollments en on en.cedula=sr.cedula
 where sr.cedula=btrim(p_cedula) and en.subject='Programación I' limit 1;
 if not found then return jsonb_build_object('ok',false,'message','No estás matriculado en Programación I.'); end if;
 select ep.* into v_pub from exam_publications ep join exams e on e.id=ep.exam_id
 where ep.group_name=v_student.group_name and ep.active=true and e.subject='Programación I'
 order by ep.published_at desc limit 1;
 if not found then return jsonb_build_object('ok',false,'message','No hay una evaluación activa para tu grupo.'); end if;
 if exists(select 1 from exam_results where exam_id=v_pub.exam_id and cedula=v_student.cedula and group_name=v_student.group_name) then
   return jsonb_build_object('ok',false,'message','Esta evaluación ya fue presentada.');
 end if;
 select * into v_exam from exams where id=v_pub.exam_id;
 select jsonb_agg(jsonb_build_object('q',x->>'q','o',x->'o')) into v_q from jsonb_array_elements(v_exam.questions) x;
 return jsonb_build_object('ok',true,'exam_id',v_exam.id,'title',v_exam.title,'student_name',v_student.name,'group_name',v_student.group_name,'questions',v_q);
end;$$;
grant execute on function public.get_active_exam(text) to anon,authenticated;

create or replace function public.submit_exam(p_exam_id bigint,p_cedula text,p_answers jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_student record; v_exam record; v_total int; v_correct int:=0; v_i int; v_grade numeric(3,2); v_status text;
begin
 select sr.cedula,sr.name,en.group_name into v_student from student_registry sr join student_enrollments en on en.cedula=sr.cedula
 where sr.cedula=btrim(p_cedula) and en.subject='Programación I' limit 1;
 if not found then raise exception 'Estudiante no válido para Programación I'; end if;
 if not exists(select 1 from exam_publications where exam_id=p_exam_id and group_name=v_student.group_name and active=true) then raise exception 'La evaluación no está activa para este grupo'; end if;
 if exists(select 1 from exam_results where exam_id=p_exam_id and cedula=v_student.cedula and group_name=v_student.group_name) then raise exception 'La evaluación ya fue presentada'; end if;
 select * into v_exam from exams where id=p_exam_id; v_total=jsonb_array_length(v_exam.questions);
 if jsonb_array_length(p_answers)<>v_total then raise exception 'Debes responder todas las preguntas'; end if;
 for v_i in 0..v_total-1 loop
   if (p_answers->>v_i)::int = ((v_exam.questions->v_i)->>'a')::int then v_correct=v_correct+1; end if;
 end loop;
 v_grade=round((v_correct::numeric/v_total::numeric)*5.0,2); v_status=case when v_grade>=3.0 then 'APROBÓ' else 'PERDIÓ' end;
 insert into exam_results(exam_id,cedula,student_name,group_name,correct_answers,total_questions,grade,status)
 values(p_exam_id,v_student.cedula,v_student.name,v_student.group_name,v_correct,v_total,v_grade,v_status);
 -- La nota NO se devuelve al estudiante; queda solo en el panel docente.
 return jsonb_build_object('ok',true,'message','Evaluación enviada correctamente. Tu calificación quedó registrada para el docente.');
end;$$;
grant execute on function public.submit_exam(bigint,text,jsonb) to anon,authenticated;
